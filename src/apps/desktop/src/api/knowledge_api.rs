#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct UpsertKnowledgeEntryRequest {
    /// Omit to create a new entry; the id is generated by the store caller.
    #[serde(default)]
    pub entry_id: Option<String>,
    pub knowledge_base_id: String,
    pub title: String,
    pub body: String,
    #[serde(default)]
    pub tags: String,
    #[serde(default)]
    pub source: Option<String>,
    #[serde(default)]
    pub reason: Option<String>,
}

#[tauri::command]
pub async fn upsert_knowledge_entry(
    request: UpsertKnowledgeEntryRequest,
) -> Result<KnowledgeEntryUpsertOutcome, String> {
    let knowledge_base_id = non_empty(&request.knowledge_base_id, "Knowledge base id")?;
    let title = non_empty(&request.title, "Title")?;
    let entry_id = match request.entry_id.as_deref().map(str::trim) {
        Some(id) if !id.is_empty() => id.to_string(),
        _ => uuid::Uuid::new_v4().to_string(),
    };
    knowledge_database()
        .upsert_knowledge_entry(KnowledgeEntryUpsert {
            id: entry_id,
            knowledge_base_id,
            title,
            body: request.body,
            tags: request.tags.trim().to_string(),
            source: request.source.filter(|value| !value.trim().is_empty()),
            actor: KnowledgeActor::user(),
            reason: request.reason.filter(|value| !value.trim().is_empty()),
        })
        .await
        .map_err(|error| error.to_string())
}

