//! Knowledge base management API.
//!
//! Knowledge bases are a user-level local resource (`~/.config/opcteam/data/knowledge/knowledge.sqlite`,
//! resolved through `PathManager::knowledge_database_file`). They are not owned
//! by a workspace, so these commands take no workspace reference and behave the
//! same for every workspace kind. Remote workspaces still edit the local store:
//! the database lives on this machine, next to the user's other user-level data.
//!
//! Agents read and write knowledge through the `KnowledgeSearch` / `KnowledgeRead`
//! / `KnowledgeWrite` tools; these commands are the human-facing CRUD surface.

use opc_core::agentic::knowledge::{
    KnowledgeActor, KnowledgeBaseRecord, KnowledgeDatabase, KnowledgeEntryRecord,
    KnowledgeEntryUpsert, KnowledgeEntryUpsertOutcome, KnowledgeLedgerRecord,
    KnowledgeSearchChannel, KnowledgeSearchOutcome, KnowledgeSearchRequest,
};
use opc_core::infrastructure::get_path_manager_arc;
use serde::Deserialize;

fn knowledge_database() -> KnowledgeDatabase {
    KnowledgeDatabase::new(get_path_manager_arc())
}

fn non_empty(value: &str, field: &str) -> Result<String, String> {
    let trimmed = value.trim();
    if trimmed.is_empty() {
        return Err(format!("{field} cannot be empty"));
    }
    Ok(trimmed.to_string())
}

#[tauri::command]
pub async fn list_knowledge_bases() -> Result<Vec<KnowledgeBaseRecord>, String> {
    knowledge_database()
        .list_knowledge_bases()
        .await
        .map_err(|error| error.to_string())
}

#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct CreateKnowledgeBaseRequest {
    pub name: String,
    #[serde(default)]
    pub description: String,
}

#[tauri::command]
pub async fn create_knowledge_base(
    request: CreateKnowledgeBaseRequest,
) -> Result<KnowledgeBaseRecord, String> {
    let name = non_empty(&request.name, "Name")?;
    knowledge_database()
        .create_knowledge_base(&name, request.description.trim())
        .await
        .map_err(|error| error.to_string())
}

#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct UpdateKnowledgeBaseRequest {
    pub knowledge_base_id: String,
    pub name: String,
    #[serde(default)]
    pub description: String,
}

#[tauri::command]
pub async fn update_knowledge_base(
    request: UpdateKnowledgeBaseRequest,
) -> Result<KnowledgeBaseRecord, String> {
    let id = non_empty(&request.knowledge_base_id, "Knowledge base id")?;
    let name = non_empty(&request.name, "Name")?;
    knowledge_database()
        .rename_knowledge_base(&id, &name, request.description.trim())
        .await
        .map_err(|error| error.to_string())
}

#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct DeleteKnowledgeBaseRequest {
    pub knowledge_base_id: String,
}

/// Delete a knowledge base with every entry and its ledger history.
///
/// Destructive removal stays an explicit user action: nothing else in the
/// product calls this, and agents cannot reach it through a tool.
#[tauri::command]
pub async fn delete_knowledge_base(request: DeleteKnowledgeBaseRequest) -> Result<bool, String> {
    let id = non_empty(&request.knowledge_base_id, "Knowledge base id")?;
    knowledge_database()
        .delete_knowledge_base(&id)
        .await
        .map_err(|error| error.to_string())
}

